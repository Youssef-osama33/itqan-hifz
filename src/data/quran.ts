export const TOTAL_QURAN_PAGES = 604;

export const ALL_SURAHS: SurahData[] = RAW_SURAHS.map((row, idx) => {
  const [id, name, ayahs, startPage, juz] = row;
  const nextStart = idx < RAW_SURAHS.length - 1 ? RAW_SURAHS[idx + 1][3] : 605;
  const rawDiff = nextStart - startPage;
  const pages = rawDiff > 0 ? rawDiff : 0.4;
  return { id, name, ayahs, startPage, pages, juz };
});

export function getOrderedSurahs(startSurahId: number): SurahData[] {
  const clamped = Math.min(114, Math.max(1, startSurahId));
  const phase1 = ALL_SURAHS.filter((s) => s.id >= clamped);
  const phase2 = ALL_SURAHS.filter((s) => s.id < clamped);
  return [...phase1, ...phase2];
}
